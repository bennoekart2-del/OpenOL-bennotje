/*
 * One owner for every map enemy (OpenOL 2.1.0, OLGame.exe sha256 2e58afbb...).
 *
 * The bug: every client runs the AI copy of a map-placed enemy and sends it to the others, and every client turns the copy it receives
 * into a second, puppet enemy. Players see two enemies at one place.
 * The rule added here: when two copies of one enemy meet (same place), the copy of the client with the LOWER player id stays real; the other
 * client removes its own copy and keeps the puppet of the lower id's one. Enemies that exist on one client only are untouched.
 *
 * Two hooks, both patched into OLGame.exe by apply_patch.py:
 *   my_ApplySpawn  replaces the only direct call of the static ApplySpawn() (a spawn packet arrived from `sender`): runs the original (it makes
 *                  the puppet), then if one of our own enemies of the same class is at the puppet's place:
 *                                                              sender < me: destroy ours (keep the puppet);
 *                                                              sender > me: destroy the puppet (the sender drops its copy when it hears of ours).
 *   my_SendSpawn   replaces the virtual call UEnemyChannel::SendSpawn(E) inside TickSend (we are about to announce our enemy E):
 *                  a puppet of another client is already at E's place -> its owner < me: destroy E, announce nothing;
 *                                                                        its owner > me: destroy that puppet, announce E.
 *
 * Freestanding on purpose: no libc, no imports, no relocations. The image base comes from the PEB, so ASLR does not matter.
 * Offsets were read from the decompiled code and checked against Development/Src/Multiplayer/Src/EnemyChannel.cpp of OpenOL.
 */
#include "olfix_layout.h"   /* generated by build.py from sites.json: CAVE_RVA, DATA_OFFSET and the F_* field offsets of the data area */

typedef int i32;
typedef unsigned int u32;
typedef unsigned char u8;

static inline char *IB(void)
{
    char *p;
    __asm__ volatile("movq %%gs:0x60, %0\n\tmovq 0x10(%0), %0" : "=r"(p));
    return p;
}


/* The data area (a zeroed, writable part of the same section): a kill switch per feature that a test can set from outside, and counters it can read. */
#define OLFX_MAGIC 0x5846504Fu
#define DISABLE_ONE_OWNER 1u
#define DISABLE_MAILBOX   2u
#define DISABLE_SHARED_CP 4u
#define DISABLE_TRIGGER_NEAR 8u
static inline volatile u32 *data_area(char *ib)
{
    volatile u32 *d = (volatile u32 *)(ib + CAVE_RVA + DATA_OFFSET);
    if (d[F_MAGIC / 4] == 0) {
        d[F_VERSION / 4] = 2;
        d[F_MAGIC / 4] = OLFX_MAGIC;
    }
    return d;
}
static inline void bump(volatile u32 *d, u32 field)
{
    d[field / 4] = d[field / 4] + 1;
}

#define RVA_TICK          0x174f1d0   /* UBOOL AOLPlayerController::Tick(FLOAT dt, ELevelTick) : the per-frame game-thread hook (vtable slot +0x350) */
#define RVA_EXECCP        0x1707020   /* the overlay's checkpoint loader ExecCP_GameThread(void): reads the two buffers below, loads in this world or changes the map */
#define RVA_CPNAME        0x3677fd0   /* char[128] GCPPendingName */
#define RVA_CPPERSIST     0x3678050   /* char[128] GCPPendingPersist */
#define RVA_SNGAC         0x174e830   /* void AOLPlayerController::StartNewGameAtCheckpoint(const FString& name, UBOOL bSave) (vtable +0xa88) */
#define RVA_SENDBINARY    0x174d9b0   /* FMpConnection::SendBinary(FMpConnection*, const BYTE* data, INT count): the wire adds the player id after the type byte */
#define RVA_GMPCONN       0x36b9a30   /* FMpConnection GMpConn: +0x30 bIsConnected, +0x34 bIsHandshaked */
#define RVA_GETGAMEINFO   0x0d214c0   /* AGameInfo* UWorld::GetGameInfo(UWorld*) */
#define GAME_DIFFICULTY   0x49c       /* AOLGame::DifficultyMode (BYTE, 3 = Insane: a death restarts through StartNewGameAtCheckpoint) */
#define PC_HEROPAWN       0xa5c       /* AOLPlayerController::HeroPawn */
#define CH_WORLD          5
#define WORLD_TRIGGER_ACT 0x01        /* [countLE4][pathLen][path ASCII], + our tail [magic 'OLP1'][x f32][y f32][z f32] (old clients ignore trailing bytes) */
#define TRIG_TAIL_MAGIC   0x31504C4Fu /* 'OLP1' little endian */
#define TRIG_RADIUS_SQ_BITS 0x4b095440u /* 3000 * 3000 as float bits: the default when the data area field is 0 */
#define TRIG_QUEUE_MAX    6
#define TRIG_ENTRY_SIZE   192         /* u64 channel, i32 sender, u32 type, i32 len, f32 x y z, then up to 160 bytes of the packet */
#define TRIG_DATA_MAX     160
#define WORLD_CHECKPOINT_LOAD 0x11    /* new: [nameLen][name ASCII][persistLen][persistent level ASCII] */
#define RVA_APPLYSPAWN    0x171eb00   /* static void ApplySpawn(UEnemyChannel*, INT sender, FString& name, FString& class, FLOAT x,y,z, INT yaw, ...) */
#define RVA_DESTROYACTOR  0x08d7550   /* UBOOL UWorld::DestroyActor(AActor*, UBOOL bNetForce, UBOOL bShouldModifyLevel) */
#define RVA_GWORLD        0x30d1e58   /* UWorld* GWorld */
#define RVA_LOCALPLAYERID 0x36b9a70   /* GMpConn.LocalPlayerID */
#define RVA_SYNCENEMIES   0x36b9aec   /* GMpConn.SyncEnemies */

#define CH_CONTROLLER     0x60        /* UEnemyChannel::ControllerOwner */
#define CTRL_CACHED       0xe78       /* AMultiplayerController::CachedEnemies  data ptr, count at +8 */
#define CTRL_REMOTE       0xeb8       /* AMultiplayerController::RemoteEnemies  data ptr, count at +8, element size 0x44 */
#define CTRL_SENT         0xec8       /* AMultiplayerController::SentEnemySpawns  TArray<FString> (16 bytes each: TCHAR*, num, max), count at +8 */
#define RVA_APPFREE       0x0be940    /* appFree(void*) */
#define REMOTE_STRIDE     0x44
#define REMOTE_DUMMY      0x10        /* FRemoteEnemyState::DummyEnemy */
#define REMOTE_OWNER      0x18        /* FRemoteEnemyState::OwnerID */
#define ACTOR_LOC         0x80        /* AActor::Location (3 floats) */
#define PAWN_HEALTH       0x37c
#define ACTOR_FLAGS_A     0xe8        /* bit 8 = bDeleteMe */
#define ACTOR_FLAGS_B     0xec        /* bit 0x800000 = bPendingDelete */

#define OBJ_CLASS         0x50        /* UObject::Class (Index at +0x38 and Name at +0x48 were confirmed in GetName()) */
#define SAME_PLACE_SQ_BITS 0x46afc800u /* 150 * 150 as float bits: an integer immediate, so the compiler emits no .rdata constant */

typedef void (*ApplySpawnFn)(char *, i32, void *, void *, float, float, float, i32, void *, i32, i32, float, float, float, float);
typedef void (*SendSpawnFn)(char *, char *);

static inline void destroy_actor(char *ib, char *actor)
{
    ((i32(*)(void *, void *, i32, i32))(ib + RVA_DESTROYACTOR))(*(void **)(ib + RVA_GWORLD), actor, 0, 1);
}

static inline int alive(const char *e)
{
    return *(i32 *)(e + PAWN_HEALTH) > 0 && !(*(u8 *)(e + ACTOR_FLAGS_A) & 8) && !(*(u32 *)(e + ACTOR_FLAGS_B) & 0x800000u);
}

static inline float same_place_sq(void)
{
    float k;
    __asm__("movl %1, %%eax; movd %%eax, %0" : "=x"(k) : "i"(SAME_PLACE_SQ_BITS) : "eax");
    return k;
}

static inline float dist2(const char *e, float x, float y, float z)
{
    float dx = *(const float *)(e + ACTOR_LOC) - x;
    float dy = *(const float *)(e + ACTOR_LOC + 4) - y;
    float dz = *(const float *)(e + ACTOR_LOC + 8) - z;
    return dx * dx + dy * dy + dz * dz;
}

__attribute__((noinline, used))
void my_ApplySpawn(char *ch, i32 sender, void *name, void *cls, float x, float y, float z, i32 yaw, void *mesh, i32 weapon, i32 has_color,
                   float cr, float cg, float cb, float ca)
{
    char *ib = IB();
    volatile u32 *d0 = data_area(ib);
    bump(d0, F_CNT_APPLY_CALLS);
    char *ctrl = ch ? *(char **)(ch + CH_CONTROLLER) : 0;
    i32 n0 = ctrl ? *(i32 *)(ctrl + CTRL_REMOTE + 8) : 0;
    ((ApplySpawnFn)(ib + RVA_APPLYSPAWN))(ch, sender, name, cls, x, y, z, yaw, mesh, weapon, has_color, cr, cg, cb, ca);
    if ((d0[F_DISABLE / 4] & DISABLE_ONE_OWNER) || !ctrl || !*(i32 *)(ib + RVA_SYNCENEMIES))
        return;
    i32 n1 = *(i32 *)(ctrl + CTRL_REMOTE + 8);
    if (n1 <= n0)
        return;                                   /* the original ignored the packet (already known) */
    char *r = *(char **)(ctrl + CTRL_REMOTE) + (long long)(n1 - 1) * REMOTE_STRIDE;
    char *d = *(char **)(r + REMOTE_DUMMY);       /* the puppet the original just made */
    if (!d)
        return;
    char **arr = *(char ***)(ctrl + CTRL_CACHED);
    i32 n = *(i32 *)(ctrl + CTRL_CACHED + 8);
    for (i32 i = 0; arr && i < n; i++) {
        char *e = arr[i];
        if (!e || e == d || !alive(e) || *(void **)(e + OBJ_CLASS) != *(void **)(d + OBJ_CLASS) || dist2(e, *(float *)(d + ACTOR_LOC), *(float *)(d + ACTOR_LOC + 4), *(float *)(d + ACTOR_LOC + 8)) >= same_place_sq())
            continue;
        if (sender > *(i32 *)(ib + RVA_LOCALPLAYERID)) {
            *(char **)(r + REMOTE_DUMMY) = 0;     /* ours is the real one: no puppet of the sender's copy */
            destroy_actor(ib, d);
            bump(d0, F_CNT_PUPPET_DESTROYED);
            *(char *volatile *)((volatile char *)d0 + F_REBROADCAST_CTRL) = ctrl;   /* the sender may have missed our announcement while it loaded: announce again */
        } else {
            destroy_actor(ib, e);                 /* the sender's is the real one: drop our copy, keep the puppet */
            bump(d0, F_CNT_OWN_DESTROYED);
        }
        break;
    }
}

__attribute__((noinline, used))
void my_SendSpawn(char *ch, char *e)
{
    char *ib = IB();
    volatile u32 *d0 = data_area(ib);
    bump(d0, F_CNT_SEND_CALLS);
    char *ctrl = ch ? *(char **)(ch + CH_CONTROLLER) : 0;
    if (!(d0[F_DISABLE / 4] & DISABLE_ONE_OWNER) && ctrl && e && *(i32 *)(ib + RVA_SYNCENEMIES)) {
        char *rem = *(char **)(ctrl + CTRL_REMOTE);
        i32 n = *(i32 *)(ctrl + CTRL_REMOTE + 8);
        float x = *(float *)(e + ACTOR_LOC), y = *(float *)(e + ACTOR_LOC + 4), z = *(float *)(e + ACTOR_LOC + 8);
        for (i32 i = 0; rem && i < n; i++) {
            char *r = rem + (long long)i * REMOTE_STRIDE;
            char *d = *(char **)(r + REMOTE_DUMMY);
            if (!d || *(void **)(d + OBJ_CLASS) != *(void **)(e + OBJ_CLASS) || dist2(d, x, y, z) >= same_place_sq())
                continue;
            if (*(i32 *)(r + REMOTE_OWNER) < *(i32 *)(ib + RVA_LOCALPLAYERID)) {
                destroy_actor(ib, e);        /* a lower id owns this enemy: ours is the duplicate */
                bump(d0, F_CNT_OWN_DESTROYED);
                return;
            }
            *(char **)(r + REMOTE_DUMMY) = 0;
            destroy_actor(ib, d);            /* a higher id's puppet: ours is the real one */
            bump(d0, F_CNT_PUPPET_DESTROYED);
            *(char *volatile *)((volatile char *)d0 + F_REBROADCAST_CTRL) = ctrl;   /* make sure the owner of that puppet hears of ours */
            break;
        }
    }
    /* the original SendSpawn, found through the vtable the patched call site no longer reads */
    char *vt = *(char **)ch;
    (*(SendSpawnFn *)(vt + 0x268))(ch, e);
}

typedef void (*WorldPacketFn)(char *, i32, u32, const u8 *, i32);

/* ---- Story triggers only for players near them (patch v6) ----
 * The bug: a trigger touched by one player is force-activated on every client, wherever its hero is (a scripted scene can start for a partner on another
 * floor). The rule: the sender appends where it stood when it touched the trigger; a receiver whose hero is farther than the radius keeps the packet in a
 * small queue and applies it once its own hero comes within the radius. Packets without the tail (an unpatched sender) and an unknown own position fail
 * open (applied at once, as before). The queue is dropped on every checkpoint load and when the local controller changes (a new map). */
static inline float u2f(u32 bits)
{
    float k;
    __asm__("movd %1, %0" : "=x"(k) : "r"(bits));
    return k;
}

static inline float trig_radius_sq(volatile u32 *d)
{
    u32 b = d[F_TRIG_RADIUS_SQ / 4];
    if (b == 0) {
        __asm__("movl %1, %0" : "=r"(b) : "i"(TRIG_RADIUS_SQ_BITS));
    }
    return u2f(b);
}

static inline int hero_near(volatile u32 *d, float x, float y, float z)
{
    float dx = u2f(d[F_HERO_X / 4]) - x, dy = u2f(d[F_HERO_Y / 4]) - y, dz = u2f(d[F_HERO_Z / 4]) - z;
    return dx * dx + dy * dy + dz * dz <= trig_radius_sq(d);
}

static void trig_queue_clear(volatile u32 *d)
{
    u32 n = d[F_TRIG_COUNT / 4];
    d[F_TRIG_COUNT / 4] = 0;
    d[F_CNT_TRIG_CLEARED / 4] = d[F_CNT_TRIG_CLEARED / 4] + n;
}

/* Sender side: replaces the call of FMpConnection::SendBinary in SendWorldIntString (only ever used for WORLD_TRIGGER_ACT): append our hero position. */
__attribute__((noinline, used))
void my_SendTrigger(void *conn, const u8 *b, i32 n)
{
    char *ib = IB();
    volatile u32 *d = data_area(ib);
    u8 buf[TRIG_DATA_MAX + 2 + 16];
    volatile u8 *vb = buf;                                               /* volatile: keeps the compiler from turning the copies into a memcpy call */
    if (b && n >= 7 && n <= TRIG_DATA_MAX + 2 && b[0] == CH_WORLD && b[1] == WORLD_TRIGGER_ACT && d[F_HERO_VALID / 4]) {
        for (i32 i = 0; i < n; i++)
            vb[i] = b[i];
        *(volatile u32 *)(vb + n) = TRIG_TAIL_MAGIC;
        *(volatile u32 *)(vb + n + 4) = d[F_HERO_X / 4];
        *(volatile u32 *)(vb + n + 8) = d[F_HERO_Y / 4];
        *(volatile u32 *)(vb + n + 12) = d[F_HERO_Z / 4];
        bump(d, F_CNT_TRIG_SENT_POS);
        b = buf;
        n += 16;
    }
    ((void (*)(void *, const u8 *, i32))(ib + RVA_SENDBINARY))(conn, b, n);
}

/* Receiver side, called from my_WorldPacket for WORLD_TRIGGER_ACT. Returns 1 when the packet was queued (not applied now). */
static int trig_maybe_defer(volatile u32 *d, char *ch, i32 sender, u32 type, const u8 *data, i32 len)
{
    bump(d, F_CNT_TRIG_RECV);
    if ((d[F_DISABLE / 4] & DISABLE_TRIGGER_NEAR) || !data || len < 5 || !d[F_HERO_VALID / 4])
        return 0;
    i32 base = 5 + data[4];
    if (len != base + 16 || *(const u32 *)(data + base) != TRIG_TAIL_MAGIC)
        return 0;                                                        /* no position: an unpatched sender */
    float x = *(const float *)(data + base + 4), y = *(const float *)(data + base + 8), z = *(const float *)(data + base + 12);
    if (hero_near(d, x, y, z))
        return 0;
    u32 k = d[F_TRIG_COUNT / 4];
    if (k >= TRIG_QUEUE_MAX || base > TRIG_DATA_MAX) {
        bump(d, F_CNT_TRIG_OVERFLOW);                                    /* fail open: apply now, as upstream does */
        return 0;
    }
    volatile char *e = (volatile char *)d + F_TRIG_QUEUE + k * TRIG_ENTRY_SIZE;
    *(char *volatile *)e = ch;
    *(volatile i32 *)(e + 8) = sender;
    *(volatile u32 *)(e + 12) = type;
    *(volatile i32 *)(e + 16) = base;                                    /* replayed without the tail */
    *(volatile float *)(e + 20) = x;
    *(volatile float *)(e + 24) = y;
    *(volatile float *)(e + 28) = z;
    for (i32 i = 0; i < base; i++)
        e[32 + i] = (char)data[i];
    d[F_TRIG_COUNT / 4] = k + 1;
    bump(d, F_CNT_TRIG_DEFERRED);
    return 1;
}

/* Per frame: remember where our hero is, and apply the queued triggers we have come near to (all of them when the feature is switched off). */
static void trig_tick(volatile u32 *d, char *pc)
{
    char *hero = pc ? *(char **)(pc + PC_HEROPAWN) : 0;
    char *owner = *(char *volatile *)((volatile char *)d + F_TRIG_PC);
    if (!hero) {                                                         /* no hero (loading, respawn, a controller that is not the player's): skip */
        if (pc == owner)
            d[F_HERO_VALID / 4] = 0;
        return;
    }
    if (owner != pc) {                                                   /* another controller with a hero: a new map, the queued channel pointers are stale */
        *(char *volatile *)((volatile char *)d + F_TRIG_PC) = pc;
        trig_queue_clear(d);
    }
    d[F_HERO_X / 4] = *(u32 *)(hero + ACTOR_LOC);
    d[F_HERO_Y / 4] = *(u32 *)(hero + ACTOR_LOC + 4);
    d[F_HERO_Z / 4] = *(u32 *)(hero + ACTOR_LOC + 8);
    d[F_HERO_VALID / 4] = 1;
    u32 n = d[F_TRIG_COUNT / 4];
    if (!n)
        return;
    int all = (d[F_DISABLE / 4] & DISABLE_TRIGGER_NEAR) != 0;
    u32 w = 0;
    for (u32 i = 0; i < n; i++) {
        volatile char *e = (volatile char *)d + F_TRIG_QUEUE + i * TRIG_ENTRY_SIZE;
        if (all || hero_near(d, *(volatile float *)(e + 20), *(volatile float *)(e + 24), *(volatile float *)(e + 28))) {
            char *ch = *(char *volatile *)e;
            bump(d, F_CNT_TRIG_REPLAYED);
            (*(WorldPacketFn *)(*(char **)ch + 0x298))(ch, *(volatile i32 *)(e + 8), *(volatile u32 *)(e + 12), (const u8 *)(e + 32), *(volatile i32 *)(e + 16));
            continue;
        }
        if (w != i)
            for (u32 j = 0; j < TRIG_ENTRY_SIZE; j++)
                ((volatile char *)d + F_TRIG_QUEUE + w * TRIG_ENTRY_SIZE)[j] = e[j];
        w++;
    }
    d[F_TRIG_COUNT / 4] = w;
}

typedef i32 (*TickFn)(char *, float, i32);
typedef void (*SNGACFn)(char *, void *, i32);

static int same_name(const volatile char *a, const unsigned short *w, i32 wn)
{
    i32 i = 0;
    for (; i < wn && w[i]; i++)
        if (i >= 127 || a[i] != (char)w[i])
            return 0;
    return a[i] == 0;
}

/* the persistent level of a checkpoint, from the prefix table the applier wrote into the data area (no string constants in the code) */
static const volatile char *persist_of(volatile u32 *d, const char *name)
{
    const volatile char *t = (const volatile char *)d + F_PERSIST_TABLE;
    while (*t) {
        const volatile char *pre = t, *per;
        i32 k = 0;
        while (pre[k] && name[k] == pre[k])
            k++;
        while (*t) t++;
        per = ++t;
        while (*t) t++;
        t++;
        if (pre[k] == 0)
            return per;
    }
    return t;   /* the empty string: unknown group, same-world loads still work */
}

static void copy_cstr(char *dst, const volatile char *src, u32 max)
{
    u32 i = 0;
    for (; i + 1 < max && src[i]; i++)
        dst[i] = src[i];
    dst[i] = 0;
}

/* The command mailbox: a test writes a command into the data area from outside, this hook (game thread, once per frame, outside the network poll) runs it. */
__attribute__((noinline, used))
i32 my_Tick(char *pc, float dt, i32 type)
{
    char *ib = IB();
    volatile u32 *d = data_area(ib);
    trig_tick(d, pc);
    char *rb = *(char *volatile *)((volatile char *)d + F_REBROADCAST_CTRL);
    if (rb) {                                                            /* announce all our enemies again: empty the 'already announced' list */
        *(char *volatile *)((volatile char *)d + F_REBROADCAST_CTRL) = 0;
        if (rb == pc) {                                                  /* only the controller that set it, and only from its own Tick */
            char *items = *(char **)(rb + CTRL_SENT);
            i32 n = *(i32 *)(rb + CTRL_SENT + 8);
            for (i32 i = 0; items && i < n; i++) {
                void *str = *(void **)(items + 16 * (long long)i);
                if (str)
                    ((void (*)(void *))(ib + RVA_APPFREE))(str);
            }
            *(i32 *)(rb + CTRL_SENT + 8) = 0;                            /* ArrayNum = 0: the next TickSend sends every live enemy again */
            bump(d, F_CNT_REBROADCAST);
        }
    }
    if (d[F_FOLLOW_PENDING / 4]) {                                       /* a partner loaded a checkpoint: do the same here */
        d[F_FOLLOW_PENDING / 4] = 0;
        if (!(d[F_DISABLE / 4] & DISABLE_SHARED_CP)) {
            copy_cstr((char *)d + F_EXPECT_NAME, (const volatile char *)d + F_FOLLOW_NAME, 128);
            copy_cstr(ib + RVA_CPNAME, (const volatile char *)d + F_FOLLOW_NAME, 128);
            copy_cstr(ib + RVA_CPPERSIST, (const volatile char *)d + F_FOLLOW_PERSIST, 128);
            bump(d, F_CNT_FOLLOW_EXEC);
            ((void (*)(void))(ib + RVA_EXECCP))();
        }
    }
    u32 seq = d[F_CMD_SEQ / 4];
    if (seq != d[F_RES_SEQ / 4] && !(d[F_DISABLE / 4] & DISABLE_MAILBOX)) {
        i32 code = 2;
        if (d[F_CMD / 4] == 1) {                                         /* LOAD_CHECKPOINT: name NUL persistent NUL */
            volatile char *arg = (volatile char *)(d + F_CMD_ARG / 4);
            u32 len = d[F_CMD_ARG_LEN / 4], n = 0;
            while (n < len && n < 255 && arg[n])
                n++;
            if (n == 0 || n >= 128 || n >= len) {
                code = 3;
            } else {
                copy_cstr(ib + RVA_CPNAME, arg, 128);
                copy_cstr(ib + RVA_CPPERSIST, arg + n + 1, 128);
                d[F_RES_CODE / 4] = 0;
                d[F_RES_SEQ / 4] = seq;                                  /* answer before the call: the load may replace the world */
                ((void (*)(void))(ib + RVA_EXECCP))();
                code = -1;
            }
        }
        if (code >= 0) {
            d[F_RES_CODE / 4] = (u32)code;
            d[F_RES_SEQ / 4] = seq;
        }
    }
    return ((TickFn)(ib + RVA_TICK))(pc, dt, type);
}

/* Every checkpoint load passes here (menu, overlay, the mailbox, a deferred cross-map load, an Insane death restart). Tell the partners, unless it is a
   death restart or the partner's own load we are executing (echo guard). */
__attribute__((noinline, used))
void my_SNGAC(char *pc, void *fname, i32 bsave)
{
    char *ib = IB();
    volatile u32 *d = data_area(ib);
    char *hero = pc ? *(char **)(pc + PC_HEROPAWN) : 0;
    int dying = hero && *(i32 *)(hero + PAWN_HEALTH) <= 0;
    trig_queue_clear(d);                                                 /* triggers of the old place must not fire in the new one */
    ((SNGACFn)(ib + RVA_SNGAC))(pc, fname, bsave);
    const unsigned short *w = fname ? *(const unsigned short **)fname : 0;
    i32 wn = fname ? *(i32 *)((char *)fname + 8) : 0;
    char *conn = ib + RVA_GMPCONN;
    if (!w || wn <= 1 || (d[F_DISABLE / 4] & DISABLE_SHARED_CP) || !*(i32 *)(conn + 0x30) || !*(i32 *)(conn + 0x34))
        return;
    if (((volatile char *)d)[F_EXPECT_NAME]) {
        int echo = same_name((const volatile char *)d + F_EXPECT_NAME, w, wn);
        ((volatile char *)d)[F_EXPECT_NAME] = 0;
        if (echo) {
            bump(d, F_CNT_ECHO_SUPPRESSED);
            return;
        }
    }
    char *game = ((char *(*)(void *))(ib + RVA_GETGAMEINFO))(*(void **)(ib + RVA_GWORLD));
    if (dying || (game && *(u8 *)(game + GAME_DIFFICULTY) == 3))
        return;
    char buf[2 + 1 + 127 + 1 + 127];
    char name[128];
    i32 n = 0;
    for (; n < 127 && n < wn && w[n]; n++)
        name[n] = (char)(w[n] < 128 ? w[n] : '?');
    name[n] = 0;
    const volatile char *per = persist_of(d, name);
    i32 pn = 0;
    while (pn < 127 && per[pn])
        pn++;
    i32 k = 0;
    buf[k++] = CH_WORLD;
    buf[k++] = WORLD_CHECKPOINT_LOAD;
    buf[k++] = (char)n;
    for (i32 i = 0; i < n; i++) buf[k++] = name[i];
    buf[k++] = (char)pn;
    for (i32 i = 0; i < pn; i++) buf[k++] = per[i];
    ((void (*)(void *, const char *, i32))(ib + RVA_SENDBINARY))(conn, buf, k);
    bump(d, F_CNT_FOLLOW_SENT);
}

/* The world packets: WORLD_CHECKPOINT_LOAD is new and handled here (stored, run by the next frame); everything else goes to the original handler. */
__attribute__((noinline, used))
void my_WorldPacket(char *ch, i32 sender, u32 type, const u8 *data, i32 len)
{
    char *ib = IB();
    volatile u32 *d = data_area(ib);
    if ((type & 0xff) == WORLD_TRIGGER_ACT && trig_maybe_defer(d, ch, sender, type, data, len))
        return;
    if ((type & 0xff) != WORLD_CHECKPOINT_LOAD) {
        char *vt = *(char **)ch;
        (*(WorldPacketFn *)(vt + 0x298))(ch, sender, type, data, len);
        return;
    }
    bump(d, F_CNT_FOLLOW_RECV);
    if (!data || len < 2 || (d[F_DISABLE / 4] & DISABLE_SHARED_CP))
        return;
    i32 n = data[0];
    if (n == 0 || n > 127 || 1 + n + 1 > len)
        return;
    i32 pn = data[1 + n];
    if (pn > 127 || 1 + n + 1 + pn > len)
        return;
    volatile char *fn = (volatile char *)d + F_FOLLOW_NAME, *fp = (volatile char *)d + F_FOLLOW_PERSIST;
    for (i32 i = 0; i < n; i++) fn[i] = (char)data[1 + i];
    fn[n] = 0;
    for (i32 i = 0; i < pn; i++) fp[i] = (char)data[2 + n + i];
    fp[pn] = 0;
    d[F_FOLLOW_PENDING / 4] = 1;
}
